#!/usr/bin/env node
/**
 * apply-ios-project-overrides.js — idempotent post-init overrides for the
 * generated iOS Xcode project (src-tauri/gen/apple).
 *
 * POLICY (docs/release/ios-generated-project.md): `src-tauri/gen/apple` is
 * COMMITTED, mirroring the gen/android precedent. It is regenerated with
 * `npm run tauri:ios:init` (tauri ios init --ci), and every project
 * modification MUST flow through this script so a regeneration never
 * silently loses configuration. Never hand-edit project.pbxproj XML.
 *
 * Usage:  node scripts/apply-ios-project-overrides.js
 *
 * What it applies (all idempotent):
 *   - Display name "Plethora", bundle id com.plethora.app (verified)
 *   - iPhone + iPad device families (TARGETED_DEVICE_FAMILY "1,2")
 *   - iOS deployment target 14.0
 *   - Icon asset catalog sync from src-tauri/icons/ios/AppIcon-*.png
 *   - Marketing version (CFBundleShortVersionString / CFBundleVersion) from
 *     src-tauri/tauri.conf.json
 *   - Minimal entitlements (no unneeded capabilities)
 *   - Placeholder Info.plist markers for Proposal C (privacy purpose strings)
 *     and Proposal E (share extension)
 *
 * ─── DATA-FILE HOOKS (cross-proposal contracts) ─────────────────────────────
 *
 * Proposal C (privacy) — scripts/ios-overrides/privacy-manifest.json:
 *   {
 *     "privacyManifestSourcePath": "src/lib/privacy/PrivacyInfo.xcprivacy",
 *     "purposeStrings": { "NSSomeUsageDescription": "…" }
 *   }
 * When present, the manifest is copied into the app target and purpose
 * strings are injected into Info.plist (replacing the TODO-C placeholder).
 *
 * Proposal E (share extension) — scripts/ios-overrides/share-extension.target.json:
 *   {
 *     "targetName": "plethora-share-extension",
 *     "bundleIdSuffix": "share",           // → com.plethora.app.<suffix>
 *     "appGroup": "group.com.plethora.app.shared",
 *     "deploymentTarget": "14.0",
 *     "infoPlist": { "NSExtension": { … } },   // merged into extension plist
 *     "entitlements": { … },                   // extension entitlements dict
 *     "sourceFiles": "ShareExtension/Sources"  // xcodegen source path
 *   }
 * When present, the App Group is added to the main app entitlements and a
 * generated xcodegen target stanza (marker-delimited) is written into
 * project.yml. E must NOT edit gen/apple directly — author the JSON instead.
 *
 * When a data file is absent, clearly-marked TODO-C / TODO-E placeholders
 * are left in the generated project instead. Do NOT block on those files.
 * ───────────────────────────────────────────────────────────────────────────
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");

export const DEFAULTS = {
  displayName: "Plethora",
  bundleId: "com.plethora.app",
  deploymentTarget: "14.0",
  deviceFamilies: "1,2",
  iconsSourceDir: join(REPO_ROOT, "src-tauri", "icons", "ios"),
  tauriConfPath: join(REPO_ROOT, "src-tauri", "tauri.conf.json"),
};

const TODO_C_MARKER = "TODO-C(privacy-manifest)";
const TODO_E_MARKER = "TODO-E(share-extension)";
const EXT_TARGET_BEGIN = "// BEGIN ios-share-extension (generated by scripts/apply-ios-project-overrides.js — do not hand-edit)";
const EXT_TARGET_END = "// END ios-share-extension";

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function readText(path) {
  return readFileSync(path, "utf8");
}

function writeTextIfChanged(path, content, changes, label) {
  const existing = existsSync(path) ? readText(path) : null;
  if (existing === content) return false;
  writeFileSync(path, content);
  changes.push(label);
  return true;
}

function readOptionalJson(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readText(path));
  } catch (err) {
    throw new Error(`Failed to parse ${path}: ${err.message}`);
  }
}

function readMarketingVersion(tauriConfPath) {
  const conf = JSON.parse(readText(tauriConfPath));
  if (typeof conf.version !== "string" || !conf.version) {
    throw new Error(`tauri.conf.json has no usable version field`);
  }
  return conf.version;
}

/* ── project.yml (xcodegen source of truth) ──────────────────────────────── */

export function updateProjectYml(yml, { version, overrides }) {  let out = yml;
  const applied = [];

  // Device families + deployment target: add to the iOS target's settings.base
  // block (after ENABLE_BITCODE) when not already present.
  if (!/TARGETED_DEVICE_FAMILY:/m.test(out)) {
    out = out.replace(
      /(        ENABLE_BITCODE: false\n)/,
      `$1        TARGETED_DEVICE_FAMILY: "${DEFAULTS.deviceFamilies}"\n        IPHONEOS_DEPLOYMENT_TARGET: ${DEFAULTS.deploymentTarget}\n`
    );
    applied.push("project.yml: TARGETED_DEVICE_FAMILY + IPHONEOS_DEPLOYMENT_TARGET");
  }

  // Display name in the target's info properties.
  if (!/CFBundleDisplayName:/m.test(out)) {
    out = out.replace(
      /(        LSRequiresIPhoneOS: true\n)/,
      `$1        CFBundleDisplayName: ${DEFAULTS.displayName}\n`
    );
    applied.push("project.yml: CFBundleDisplayName");
  }

  // Marketing version — keeps regenerated projects in lockstep with
  // tauri.conf.json (release.cjs later drives this via §4.4).
  const versionRe = /(CFBundleShortVersionString:\s*)([^\s#]+)/;
  const buildRe = /(CFBundleVersion:\s*"?)([^\s"#]+)"?/;
  if (versionRe.test(out) && out.match(versionRe)[2] !== version) {
    out = out.replace(versionRe, `$1${version}`);
    out = out.replace(buildRe, `$1${version}"`);
    applied.push(`project.yml: version -> ${version}`);
  }

  // Bundle id verification (generated template already sets it; fail loudly
  // if a future generator changes it).
  if (!out.includes(`PRODUCT_BUNDLE_IDENTIFIER: ${DEFAULTS.bundleId}`)) {
    throw new Error(
      `project.yml does not set PRODUCT_BUNDLE_IDENTIFIER: ${DEFAULTS.bundleId} — inspect the generator output before overriding`
    );
  }

  // Proposal E hook: generated extension target stanza (marker-delimited).
  if (overrides && overrides.shareExtension) {
    const ext = overrides.shareExtension;
    const stanza = buildExtensionTargetStanza(ext, version);
    if (out.includes(EXT_TARGET_BEGIN)) {
      const re = new RegExp(
        `${escapeRegExp(EXT_TARGET_BEGIN)}[\\s\\S]*?${escapeRegExp(EXT_TARGET_END)}\\n?`
      );
      out = out.replace(re, stanza);
    } else {
      out = out.trimEnd() + "\n" + stanza;
    }
    applied.push("project.yml: share-extension target stanza (TODO-E data applied)");
  }

  if (out === yml) return { out, applied: [] };
  return { out, applied };
}

function buildExtensionTargetStanza(ext, version) {
  const targetName = ext.targetName;
  const bundleId = `${DEFAULTS.bundleId}.${ext.bundleIdSuffix ?? "share"}`;
  const deploymentTarget = ext.deploymentTarget ?? DEFAULTS.deploymentTarget;
  const sourceFiles = ext.sourceFiles ?? `${targetName}/Sources`;
  const lines = [
    EXT_TARGET_BEGIN,
    `targets:`,
    `  ${targetName}:`,
    `    type: app-extension`,
    `    platform: iOS`,
    `    sources:`,
    `      - path: ${sourceFiles}`,
    `    info:`,
    `      path: ${targetName}/Info.plist`,
    `      properties:`,
    `        CFBundleDisplayName: ${targetName}`,
    `        CFBundleShortVersionString: ${ext.version ?? version}`,
    `        NSExtension: ${JSON.stringify(ext.infoPlist?.NSExtension ?? {})}`,
    `    entitlements:`,
    `      path: ${targetName}/${targetName}.entitlements`,
    `      properties: ${JSON.stringify(ext.entitlements ?? {})}`,
    `    settings:`,
    `      base:`,
    `        PRODUCT_BUNDLE_IDENTIFIER: ${bundleId}`,
    `        TARGETED_DEVICE_FAMILY: "${DEFAULTS.deviceFamilies}"`,
    `        IPHONEOS_DEPLOYMENT_TARGET: ${deploymentTarget}`,
    `        SKIP_INSTALL: YES`,
    EXT_TARGET_END,
    "",
  ];
  return lines.join("\n");
}

/* ── Info.plist ──────────────────────────────────────────────────────────── */

export function updateInfoPlist(plist, { version, purposeStrings }) {
  let out = plist;
  const applied = [];
  // Insertion anchor: entries are tab-indented; the dict closes at column 0.
  const insertBeforeDictClose = (block) => out.replace(/\n<\/dict>\n<\/plist>/, `\n${block}</dict>\n</plist>`);

  if (!/<key>CFBundleDisplayName<\/key>/.test(out)) {
    const next = insertBeforeDictClose(`\t<key>CFBundleDisplayName</key>\n\t<string>${DEFAULTS.displayName}</string>\n`);
    if (next !== out) {
      out = next;
      applied.push("Info.plist: CFBundleDisplayName");
    }
  }

  const versionRe = /(<key>CFBundleShortVersionString<\/key>\n\t<string>)([^<]*)(<\/string>)/;
  if (versionRe.test(out) && out.match(versionRe)[2] !== version) {
    out = out
      .replace(versionRe, `$1${version}$3`)
      .replace(/(<key>CFBundleVersion<\/key>\n\t<string>)([^<]*)(<\/string>)/, `$1${version}$3`);
    applied.push(`Info.plist: version -> ${version}`);
  }

  if (purposeStrings && Object.keys(purposeStrings).length > 0) {
    const entries = Object.entries(purposeStrings)
      .map(
        ([k, v]) =>
          `\t<key>${k}</key>\n\t<string>${String(v).replace(/&/g, "&amp;").replace(/</g, "&lt;")}</string>\n`
      )
      .join("");
    const placeholderRe = new RegExp(`\\t<!-- ${escapeRegExp(TODO_C_MARKER)}[^>]*-->\\n`);
    let next = out.replace(placeholderRe, "");
    if (!entries.split("\t<key>").slice(1).every((e) => out.includes(e.slice(0, e.indexOf("</key>"))))) {
      next = next.replace(/\n<\/dict>\n<\/plist>/, `\n${entries}</dict>\n</plist>`);
    }
    if (next !== out) {
      out = next;
      applied.push(`Info.plist: ${Object.keys(purposeStrings).length} purpose string(s) from privacy-manifest.json`);
    }
  } else if (!out.includes(TODO_C_MARKER)) {
    const next = insertBeforeDictClose(
      `\t<!-- ${TODO_C_MARKER}: purpose strings are injected by scripts/apply-ios-project-overrides.js when scripts/ios-overrides/privacy-manifest.json exists (Proposal C). -->\n`
    );
    if (next !== out) {
      out = next;
      applied.push("Info.plist: TODO-C placeholder");
    }
  }

  if (!out.includes(TODO_E_MARKER)) {
    const next = insertBeforeDictClose(
      `\t<!-- ${TODO_E_MARKER}: extension Info.plist keys are generated by scripts/apply-ios-project-overrides.js when scripts/ios-overrides/share-extension.target.json exists (Proposal E). -->\n`
    );
    if (next !== out) {
      out = next;
      applied.push("Info.plist: TODO-E placeholder");
    }
  }

  if (out === plist) return { out, applied: [] };
  return { out, applied };
}

/* ── Entitlements ────────────────────────────────────────────────────────── */

export function updateEntitlements(entitlements, { appGroup }) {
  let out = entitlements;
  const applied = [];

  if (appGroup) {
    if (!out.includes(appGroup)) {
      if (/<dict\/>/.test(out)) {
        out = out.replace(
          /<dict\/>/,
          `<dict>\n\t<key>com.apple.security.application-groups</key>\n\t<array>\n\t\t<string>${appGroup}</string>\n\t</array>\n</dict>`
        );
      } else if (!/<key>com.apple.security.application-groups<\/key>/.test(out)) {
        out = out.replace(
          /\t<\/dict>/,
          `\t<key>com.apple.security.application-groups</key>\n\t<array>\n\t\t<string>${appGroup}</string>\n\t</array>\n\t</dict>`
        );
      } else {
        out = out.replace(
          /\t<\/array>\n\t<\/dict>/,
          `\t\t<string>${appGroup}</string>\n\t</array>\n\t</dict>`
        );
      }
      applied.push("entitlements: App Group added");
    }
  } else if (!out.includes("TODO-E")) {
    // Minimal entitlements: no unneeded capabilities until C/E land.
    if (/<dict\/>/.test(out)) {
      out = out.replace(
        /<dict\/>/,
        `<!-- ${TODO_E_MARKER}: App Group entitlement is added by scripts/apply-ios-project-overrides.js when scripts/ios-overrides/share-extension.target.json exists. -->\n<dict/>`
      );
      applied.push("entitlements: TODO-E placeholder");
    }
  }

  if (out === entitlements) return { out, applied: [] };
  return { out, applied };
}

/* ── Icons ───────────────────────────────────────────────────────────────── */

export function syncIcons(appleDir, iconsSourceDir, changes) {
  const appiconset = join(appleDir, "Assets.xcassets", "AppIcon.appiconset");
  if (!existsSync(appiconset)) {
    throw new Error(`${appiconset} missing — run \`npm run tauri:ios:init\` first`);
  }
  if (!existsSync(join(appiconset, "Contents.json"))) {
    throw new Error(`AppIcon.appiconset/Contents.json missing — regenerate the project`);
  }
  let synced = 0;
  for (const name of readdirSync(iconsSourceDir)) {
    if (!/^AppIcon-.*\.png$/.test(name)) continue;
    const src = join(iconsSourceDir, name);
    if (!statSync(src).isFile()) continue;
    const dest = join(appiconset, name);
    const srcBuf = readFileSync(src);
    let needsCopy = true;
    if (existsSync(dest)) {
      needsCopy = !srcBuf.equals(readFileSync(dest));
    }
    if (needsCopy) {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, srcBuf);
      synced++;
    }
  }
  if (synced > 0) changes.push(`icons: synced ${synced} PNG(s) from src-tauri/icons/ios`);
  return synced;
}

/* ── Orchestration ───────────────────────────────────────────────────────── */

export function applyIosProjectOverrides({
  appleDir = join(REPO_ROOT, "src-tauri", "gen", "apple"),
  overridesDir = join(REPO_ROOT, "scripts", "ios-overrides"),
  iconsSourceDir = DEFAULTS.iconsSourceDir,
  tauriConfPath = DEFAULTS.tauriConfPath,
  repoRoot = REPO_ROOT,
} = {}) {
  const changes = [];

  const projectYmlPath = join(appleDir, "project.yml");
  if (!existsSync(projectYmlPath)) {
    throw new Error(
      `${projectYmlPath} not found — run \`npm run tauri:ios:init\` (tauri ios init --ci) before applying overrides`
    );
  }

  const privacyManifest = readOptionalJson(join(overridesDir, "privacy-manifest.json"));
  const shareExtension = readOptionalJson(join(overridesDir, "share-extension.target.json"));
  const version = readMarketingVersion(tauriConfPath);

  // 1. project.yml
  const yml = updateProjectYml(readText(projectYmlPath), { version, overrides: { shareExtension } });
  writeTextIfChanged(projectYmlPath, yml.out, changes, "project.yml: updated");
  changes.push(...yml.applied);

  // 2. Info.plist
  const infoPlistPath = join(appleDir, "plethora-tauri_iOS", "Info.plist");
  const purposeStrings = privacyManifest?.purposeStrings ?? null;
  const plist = updateInfoPlist(readText(infoPlistPath), { version, purposeStrings });
  writeTextIfChanged(infoPlistPath, plist.out, changes, "Info.plist: updated");
  changes.push(...plist.applied);

  // 3. Entitlements (main app; minimal unless E's App Group data exists)
  const entitlementsPath = join(appleDir, "plethora-tauri_iOS", "plethora-tauri_iOS.entitlements");
  const ent = updateEntitlements(readText(entitlementsPath), {
    appGroup: shareExtension?.appGroup ?? null,
  });
  writeTextIfChanged(entitlementsPath, ent.out, changes, "entitlements: updated");
  changes.push(...ent.applied);

  // 4. Icons
  syncIcons(appleDir, iconsSourceDir, changes);

  // 5. Privacy manifest resource (Proposal C data)
  if (privacyManifest?.privacyManifestSourcePath) {
    const src = resolve(repoRoot, privacyManifest.privacyManifestSourcePath);
    if (!existsSync(src)) {
      throw new Error(`privacy-manifest.json points at missing file: ${src}`);
    }
    const dest = join(appleDir, "plethora-tauri_iOS", basename(src));
    const buf = readFileSync(src);
    if (!existsSync(dest) || !buf.equals(readFileSync(dest))) {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, buf);
      changes.push(`privacy manifest: copied ${basename(src)} into app target`);
    }
  }

  // 6. Extension target scaffold (Proposal E data) — Info.plist + entitlements
  if (shareExtension) {
    const extDir = join(appleDir, shareExtension.targetName);
    mkdirSync(extDir, { recursive: true });
    const nsExtension = shareExtension.infoPlist?.NSExtension ?? {};
    const extPlist = `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n\t<key>NSExtension</key>\n\t<dict>\n${Object.entries(
      nsExtension
    )
      .map(([k, v]) => `\t\t<key>${k}</key>\n\t\t${JSON.stringify(v)}`)
      .join("\n")}\n\t</dict>\n</dict>\n</plist>\n`;
    writeTextIfChanged(join(extDir, "Info.plist"), extPlist, changes, "share-extension: Info.plist written");
    const extEnt = `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>${Object.entries(
      shareExtension.entitlements ?? {}
    )
      .map(
        ([k, v]) =>
          `\n\t<key>${k}</key>\n\t<array>${(Array.isArray(v) ? v : [v])
            .map((x) => `\n\t\t<string>${x}</string>`)
            .join("")}\n\t</array>`
      )
      .join("")}\n</dict>\n</plist>\n`;
    writeTextIfChanged(
      join(extDir, `${shareExtension.targetName}.entitlements`),
      extEnt,
      changes,
      "share-extension: entitlements written"
    );
  }

  return { changes };
}

function main() {
  const { changes } = applyIosProjectOverrides();
  if (changes.length === 0) {
    console.log("apply-ios-project-overrides: nothing to do (project already up to date)");
  } else {
    for (const c of changes) console.log(`  • ${c}`);
    console.log(`apply-ios-project-overrides: ${changes.length} change(s) applied`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}

#!/usr/bin/env node
/**
 * Capture the complete showcase-v2 source set from the explicit capture build.
 * Nothing is published until every required scene/layout passes readiness.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { stableJson } from "./compile-fixture-v2.mjs";
import { measureSceneHotspots } from "./capture-hotspots.mjs";
import { assertCapturePageIntegrity } from "./capture-integrity.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE_ROOT = join(ROOT, "marketing/screenshots/source/showcase-v2");
const captureUrl = process.env.MARKETING_CAPTURE_URL;
if (!captureUrl) throw new Error("MARKETING_CAPTURE_URL is required; placeholders are never generated by showcase-v2 capture");

const [catalog, policy, packageJson, fixture] = await Promise.all([
  readFile(join(ROOT, "marketing/generated/showcase-scenes-v2.json"), "utf8").then(JSON.parse),
  readFile(join(ROOT, "marketing/screenshots/capture-policy.json"), "utf8").then(JSON.parse),
  readFile(join(ROOT, "package.json"), "utf8").then(JSON.parse),
  readFile(join(ROOT, "marketing/demo-library/generated/marketing-fixture-v2.json"), "utf8").then(JSON.parse),
]);
const gitSha = execFileSync("git", ["rev-parse", "--short=12", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
const buildId = `${packageJson.version}+${gitSha}`;
const captureTime = new Date().toISOString();
const runId = `${buildId}-${captureTime.replace(/[:.]/g, "-")}`;
const systemChromium = "/Applications/Chromium.app/Contents/MacOS/Chromium";
const chromiumExecutable = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync(systemChromium) ? systemChromium : undefined);

if (catalog.metadata.theme !== policy.theme.id || policy.theme.id !== "plethora-purple") {
  throw new Error("Generated catalog and launch capture theme disagree");
}
if (stableJson(catalog.guidedPath) !== stableJson(policy.requiredGuidedPath)) {
  throw new Error("Generated catalog and approved guided path disagree");
}

const requiredCaptures = catalog.scenes.flatMap((scene) =>
  scene.layouts.filter((layout) => layout.required).map((layout) => ({ scene, layout })),
);
if (requiredCaptures.length !== 16) throw new Error(`Expected 16 required captures, received ${requiredCaptures.length}`);

await mkdir(SOURCE_ROOT, { recursive: true });
const stage = await mkdtemp(join(dirname(SOURCE_ROOT), ".showcase-v2-stage-"));
const records = [];
let published = false;
const browser = await chromium.launch({ headless: true, executablePath: chromiumExecutable });

try {
  for (const { scene, layout } of requiredCaptures) {
    console.log(`Capturing ${scene.id}/${layout.layout}`);
    const { width, height, dpr } = layout.viewport;
    const context = await browser.newContext({
      viewport: { width, height },
      deviceScaleFactor: dpr,
      locale: catalog.metadata.locale,
      timezoneId: "UTC",
      colorScheme: "light",
      reducedMotion: "reduce",
    });
    try {
      const page = await context.newPage();
      const pageErrors = [];
      const requestUrls = [];
      page.on("pageerror", (error) => pageErrors.push(error.message));
      page.on("request", (request) => requestUrls.push(request.url()));
      await page.addInitScript(() => {
        localStorage.setItem("plethora-onboarding-tour-optout", "1");
        sessionStorage.setItem("__sw_cleared__", "1");
      });
      const target = new URL(captureUrl);
      target.hash = `#/?fixture=${encodeURIComponent(catalog.metadata.fixtureId)}&scene=${encodeURIComponent(scene.id)}&layout=${encodeURIComponent(layout.layout)}`;
      await page.goto(target.toString(), { waitUntil: "domcontentloaded", timeout: 30_000 });
      await page.addStyleTag({
        content: `
          html[data-marketing-capture="true"] *,
          html[data-marketing-capture="true"] *::before,
          html[data-marketing-capture="true"] *::after {
            animation-duration: 0s !important;
            animation-delay: 0s !important;
            transition-duration: 0s !important;
            caret-color: transparent !important;
          }
        `,
      });
      await page.waitForFunction(
        () => document.body.dataset.marketingReady === "1" || document.body.dataset.marketingReady === "error",
        undefined,
        { timeout: 60_000 },
      );
      const identity = await page.evaluate(() => ({
        ready: document.body.dataset.marketingReady,
        scene: document.body.dataset.marketingScene,
        layout: document.body.dataset.marketingLayout,
        theme: document.documentElement.dataset.themeId,
        locale: document.documentElement.lang,
        error: document.body.dataset.marketingError,
      }));
      if (identity.error || identity.ready !== "1") throw new Error(`${scene.id}/${layout.layout} is not ready: ${identity.error ?? identity.ready}`);
      if (identity.scene !== scene.id || identity.layout !== layout.layout) throw new Error(`${scene.id}/${layout.layout} resolved the wrong scene identity`);
      if (identity.theme !== policy.theme.id || identity.locale !== catalog.metadata.locale) {
        throw new Error(`${scene.id}/${layout.layout} resolved theme=${identity.theme}, locale=${identity.locale}`);
      }
      if (pageErrors.length > 0) throw new Error(`${scene.id}/${layout.layout} emitted page errors: ${pageErrors.join(" | ")}`);

      await assertCapturePageIntegrity(page, {
        scene,
        layout: layout.layout,
        catalog,
        buildId,
        fixtureTitles: fixture.records.documents.map((document) => document.title),
        captureOrigin: new URL(captureUrl).origin,
        requestUrls,
      });

      const hotspots = await measureSceneHotspots(page, scene, { width, height });
      const filename = `${scene.id}--${layout.layout}.png`;
      const filePath = join(stage, filename);
      await page.screenshot({ path: filePath, fullPage: false, animations: "disabled" });
      const bytes = await readFile(filePath);
      records.push({
        sceneId: scene.id,
        layout: layout.layout,
        filename,
        sourceType: "playwright-css-viewport",
        appVersion: packageJson.version,
        gitSha,
        fixtureVersion: catalog.metadata.fixtureVersion,
        fixtureHash: catalog.metadata.fixtureHash,
        platform: "browser-pwa",
        viewport: layout.viewport,
        theme: policy.theme.id,
        locale: catalog.metadata.locale,
        captureTime,
        sourceHash: createHash("sha256").update(bytes).digest("hex"),
        intrinsicSize: { width, height },
        accessibleDescription: scene.accessibleDescription,
        hotspots,
        safeArea: { x: 0, y: 0, width: 1, height: 1 },
      });
    } finally {
      await context.close();
    }
  }

  const manifest = {
    metadata: {
      schemaVersion: 2,
      catalogId: catalog.metadata.catalogId,
      buildId,
      appVersion: packageJson.version,
      gitSha,
      fixtureId: catalog.metadata.fixtureId,
      fixtureVersion: catalog.metadata.fixtureVersion,
      fixtureHash: catalog.metadata.fixtureHash,
      platform: "browser-pwa",
      theme: policy.theme.id,
      locale: catalog.metadata.locale,
      captureTime,
      sourceType: "playwright-css-viewport",
    },
    captures: records,
  };
  await writeFile(join(stage, "showcase-capture-v2.json"), stableJson(manifest), "utf8");
  const finalDirectory = join(SOURCE_ROOT, runId);
  await rename(stage, finalDirectory);
  published = true;
  console.log(`Captured and published ${records.length} source scenes to ${finalDirectory}`);
} finally {
  await browser.close();
  if (!published) await rm(stage, { recursive: true, force: true });
}

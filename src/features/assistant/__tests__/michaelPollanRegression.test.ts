import { describe, expect, it, vi } from "vitest";
import { runAssistantTurn } from "../../../lib/ai/assistant/orchestrator";
import { captureAction } from "../contextActions/model";
import { resolveActionEnvelope } from "../contextActions/execution";
import type { LLMProviderConfig } from "../../../stores/llmProvidersStore";

describe("Michael Pollan 2-Hour Video Regression Scenario", () => {
  const providerConfig: LLMProviderConfig = {
    id: "openrouter-1",
    provider: "openrouter",
    name: "OpenRouter",
    model: "anthropic/claude-3.5-sonnet",
    apiKey: "sk-test",
    enabled: true,
    temperature: 0.7,
    maxTokens: 4096,
  };

  // Generate 2 hours (7200 seconds) of realistic Michael Pollan consciousness lecture
  const michaelPollanTranscript = [
    "[00:06] Welcome everyone. Tonight I want to discuss the nature of consciousness and psychedelic research.",
    "[00:25] We begin with William James and early philosophical inquiries into altered states of mind.",
    "[00:45] The initial phase of research in the 1950s showed immense psychiatric promise.",
    ...Array.from({ length: 300 }, (_, i) => {
      const s = 60 + i * 15;
      const m = Math.floor(s / 60);
      const sec = s % 60;
      return `[${String(m).padStart(2, "0")}:${String(sec).padStart(2, "0")}] Discussing intermediate clinical trials, neuroscience mechanisms, and patient experiences.`;
    }),
    "[58:20] SENTINEL_MID: In the middle of the lecture, Pollan introduces the Default Mode Network (DMN) as the neurological seat of the ego.",
    "[59:10] When the DMN quiets down, the brain enters a state of higher entropy and interconnectedness.",
    ...Array.from({ length: 300 }, (_, i) => {
      const s = 3600 + i * 11;
      const m = Math.floor(s / 60);
      const sec = s % 60;
      return `[${String(m).padStart(2, "0")}:${String(sec).padStart(2, "0")}] Further clinical applications in depression, palliative care, and existential distress.`;
    }),
    "[1:58:30] SENTINEL_END: In the concluding hour, Pollan reflects on how consciousness might not be solely generated by neural matter, emphasizing humility in science.",
    "[1:59:45] Thank you very much, and I will now take questions.",
  ].join("\n");

  it("ensures 'Key points' covers beginning, middle, and end across the entire 2 hours and avoids 'supplied window (00:06–00:45)'", async () => {
    const target = {
      key: "doc:pollan-consciousness",
      owner: "document:pollan-consciousness",
      kind: "document" as const,
      sourceType: "video" as const,
      documentId: "pollan-consciousness",
      title: "Michael Pollan on Consciousness (2 Hours)",
      content: michaelPollanTranscript,
      coverage: "full" as const,
      labelKey: "document",
    };

    const action = captureAction("key-points", target, "document");
    const resolvedAction = await resolveActionEnvelope(action, "openrouter", providerConfig);

    // Verify resolveActionEnvelope did NOT truncate the 2-hour transcript
    expect(resolvedAction.target.coverage).toBe("full");
    expect(resolvedAction.target.content).toContain("[1:58:30]");

    let capturedPrompt = "";

    const chatExecutor = vi.fn(async (args) => {
      capturedPrompt = JSON.stringify(args.messages);
      return {
        content: [
          "Key Takeaways from Michael Pollan's 2-Hour Lecture:",
          "1. [00:06] Historical foundation with William James and 1950s psychiatric research.",
          "2. [58:20] Default Mode Network (DMN) mediation and ego dissolution.",
          "3. [1:58:30] Scientific humility regarding whether consciousness is purely neural matter.",
        ].join("\n"),
      };
    });

    const result = await runAssistantTurn({
      action: resolvedAction,
      scope: "document",
      userQuestion: "Key points",
      sourceType: "video",
      sourceId: "pollan-consciousness",
      sourceContent: resolvedAction.target.content,
      sourceCoverage: resolvedAction.target.coverage,
      completeTranscriptSource: true,
      explicitSourceContent: false,
      provider: "openrouter",
      model: providerConfig.model,
      globalContextTokens: 50000,
      chatExecutor,
    });

    // 1. Must NOT contain the restrictive bounded-window warning
    expect(capturedPrompt).not.toContain("supplied window (00:06–00:45)");
    expect(capturedPrompt).not.toContain("SOURCE COVERAGE LIMIT: The supplied source content is only a bounded window");

    // 2. Must cover content across the entire 2 hours
    expect(result.sourceCoverage).toMatch(/^(full|hierarchical-full)$/);
    expect(result.answer).toContain("[00:06]");
    expect(result.answer).toContain("[58:20]");
    expect(result.answer).toContain("[1:58:30]");
    expect(result.answer).not.toContain("supplied window (00:06–00:45)");
  });
});

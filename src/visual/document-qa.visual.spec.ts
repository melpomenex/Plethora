import { expect, test } from "@playwright/test";

test("Document Q&A desktop and mobile interaction/visual acceptance", async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto("/src/visual/fixtures/document-qa.html");
  const composer = page.getByRole("textbox", { name: "Your question" });
  await expect(composer).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.getAttribute("data-theme-id"))).toBe("obsidian-noir");
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: ".playwright/results/qa-desktop-start-gold.png" });
  await page.getByRole("button", { name: "Compare viewpoints" }).click();
  await expect(composer).toHaveValue(/agree or disagree/);
  await expect(page.getByRole("button", { name: "Find connections" })).toBeDisabled();
  await composer.fill("");
  await page.getByRole("button", { name: "Choose sources" }).click();
  await page.getByLabel("Search your documents").fill("Spacing");
  await expect(page.getByRole("button", { name: "Spacing, Retrieval, and the Science of Remembering", exact: true })).toBeVisible();
  await page.screenshot({ path: ".playwright/results/qa-desktop-sources.png" });
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.getByRole("button", { name: "Choose sources" })).toBeFocused();

  await page.evaluate(() => window.qaHarness.scenario("conversation"));
  await page.getByText("View supporting passages").click();
  const citation = page.getByRole("button", { name: /1 How We Learn/ });
  await expect(citation).toHaveAttribute("aria-disabled", "false");
  await page.screenshot({ path: ".playwright/results/qa-desktop-evidence.png" });
  await citation.click();
  await expect.poll(() => page.evaluate(() => window.qaHarness.openedTabs().some((tab) => tab.type === "document-viewer" && tab.data?.documentId === "qa-fixture-memory"))).toBe(true);

  await page.evaluate(() => window.qaHarness.setTheme("snow"));
  await expect.poll(() => page.evaluate(() => document.documentElement.getAttribute("data-theme-id"))).toBe("snow");
  await page.screenshot({ path: ".playwright/results/qa-desktop-light.png" });
  await page.evaluate(() => window.qaHarness.scenario("start"));
  await page.setViewportSize({ width: 360, height: 800 });
  await expect(composer).toBeVisible();
  await expect(page.getByRole("button", { name: "Ask", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: ".playwright/results/qa-mobile-start.png" });
  await page.setViewportSize({ width: 360, height: 420 });
  await composer.focus();
  await expect(page.getByRole("button", { name: "Ask", exact: true })).toBeInViewport();
  await page.screenshot({ path: ".playwright/results/qa-mobile-keyboard-height.png" });
  await page.setViewportSize({ width: 360, height: 800 });
  await composer.blur();
  await page.getByRole("button", { name: "Conversations", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.screenshot({ path: ".playwright/results/qa-mobile-history.png" });
  await page.getByRole("dialog").getByText("Memory and attention", { exact: true }).click();
  await expect(composer).toHaveValue("How does attention affect recall?");
  await page.getByRole("button", { name: "Choose sources" }).click();
  await expect(page.getByRole("button", { name: "Spacing, Retrieval, and the Science of Remembering", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: ".playwright/results/qa-mobile-source-picker.png" });
  await page.keyboard.press("Escape");

  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.evaluate(() => window.qaHarness.scenario("empty-library"));
  await composer.fill("A question for later");
  await expect(page.getByRole("button", { name: "Import documents" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Ask", exact: true })).toBeDisabled();
  await page.screenshot({ path: ".playwright/results/qa-mobile-empty-library.png" });
  await page.evaluate(() => window.qaHarness.scenario("missing-source"));
  await composer.fill("What does this source say?");
  await page.getByRole("button", { name: "Ask", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("A selected source is unavailable");
  await page.screenshot({ path: ".playwright/results/qa-mobile-source-error.png" });
  await page.setViewportSize({ width: 720, height: 900 });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  await expect(page.getByRole("button", { name: "Choose sources" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: ".playwright/results/qa-zoom-200.png" });
  expect(errors).toEqual([]);
});
